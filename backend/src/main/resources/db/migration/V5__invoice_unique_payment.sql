-- ============================================================
-- V5: 发票表的"一张缴费单只能开一次票"唯一索引（T19 电子发票）
--
-- 【为什么需要这一条】
-- 卡片 581 行「待开具电子发票：展示可开票的缴费记录」把语义钉死了：
-- 一张缴费单要么还没开票（出现在待开具列表里）、要么已经开过（消失）。
-- 也就是 invoice 与 payment_record 是 **1 : 1** 关系。
-- 可是 V1:237-246 建表时**一条索引都没有**（连 idx_payment_id 都没有），
-- 这个 1:1 完全靠应用层自觉 —— 而"患者连点两次开票按钮""两个设备同时提交"
-- 是本卡一定会发生的场景，先查后写在并发下必然留两条发票。
-- 重复发票不是难看：发票编号是要交给患者去报销的东西，两张同号或两张不同号都算事故。
--
-- 【与本仓库既有规矩一致】
-- R1（就诊卡号唯一，T08）与 R2（排班三元组唯一，T11）都是同一个双层口径：
-- service 先查一次给患者友好提示（这里是 3005「该缴费单已开具过发票」），
-- 数据库唯一索引兜住并发（输家撞 DuplicateKeyException，翻译回同一个 3005）。
-- 判据一律是"受影响行数 / 索引是否命中"，不是"我查过了应该没有"。
-- 见 [[t13-refund-decisions]]、T11 的 SCHEDULE_CONFLICT(2002) 那条。
--
-- 【为什么这张表的唯一索引没有软删后遗症】
-- patient（V1:23-36）与 schedule（V1:101-113）都有 deleted 列，唯一索引不含 deleted
-- 才会导致"软删行永久占位、重排必须复活原行"那一串复杂度（T08-G/T11 都处理过）。
-- invoice 是**财务单据表**，与 recharge_record（V1:140-151）/ payment_record（V1:156-）同一族：
-- V1:237-246 根本没有 deleted 列 —— 发票只增不删（作废是二期真实开票通道的动作），
-- 所以 uk_payment_id 就是干净的 1:1 约束，不需要复活分支，也没有历史脏行。
--
-- 【存量数据安全性】
-- invoice 首版没有任何生产者：seed.sql 零行、28 张卡里没有一张写它，
-- 所以这条 ALTER 面对的是空表，不可能因为已有重复行而失败。
-- 万一某个开发环境手插过重复行，迁移会直接报错停下（这正是我们想要的：
-- 宁可起不来，也不要带着重复发票继续跑）。
-- ============================================================

ALTER TABLE `invoice`
    ADD UNIQUE KEY `uk_payment_id` (`payment_id`);
