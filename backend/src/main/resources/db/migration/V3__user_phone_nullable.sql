-- V3: user.phone 改为可空
--
-- 微信授权登录（T07）只拿得到 openid，手机号是登录之后由用户自己
-- 用短信验证码绑定的（PRD 3.1.2「添加其他号码」）。所以建号那一刻
-- 根本没有手机号，V1 的 NOT NULL 会让首次微信登录直接插库失败。
-- NULL 的语义固定为「尚未绑定手机号」，前端据此引导去绑定。
-- ============================================================

ALTER TABLE `user`
    MODIFY COLUMN `phone` VARCHAR(256) DEFAULT NULL COMMENT '手机号（AES加密，NULL=未绑定）';
